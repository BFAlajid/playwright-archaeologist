/**
 * String templates for emitted Playwright spec files.
 *
 * Kept in a dedicated module so the emitter core stays focused on
 * iteration + I/O, and so tests can assert on generated strings without
 * running the emitter end-to-end.
 *
 * Design constraints:
 *   - No runtime dependency on a template engine. Plain template literals.
 *   - All user-controlled strings that land in the file are wrapped through
 *     `escapeForSingleQuotedString` so a malicious bundle cannot inject
 *     trailing JS/TS into the emitted source.
 *   - Emitted tests import only from `@playwright/test`. Consumers supply
 *     their own Playwright install; we do not re-export anything.
 */

// ---------------------------------------------------------------------------
// Escape helpers
// ---------------------------------------------------------------------------

/**
 * Escape a string so it is safe to place inside a single-quoted TS literal.
 * Escapes backslash, single quote, newline, carriage return, and NUL.
 * Does NOT escape `$` or `\`` because we never emit into a template
 * literal.
 */
export function escapeForSingleQuotedString(input: string): string {
  return input
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\x00/g, '\\0')
    // Also escape forward slashes used as line terminators in JS source
    // (U+2028, U+2029). rare, but crashes tsc when they slip through.
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

/**
 * Escape for a JS/TS block comment. Strips `*\/` sequences so the comment
 * cannot terminate early.
 */
export function escapeForBlockComment(input: string): string {
  return input.replace(/\*\//g, '*\\/');
}

// ---------------------------------------------------------------------------
// Shared header
// ---------------------------------------------------------------------------

export interface HeaderInfo {
  bundlePath: string;
  generatedAt: string;
}

export function renderHeader(info: HeaderInfo): string {
  const bundle = escapeForBlockComment(info.bundlePath);
  const ts = escapeForBlockComment(info.generatedAt);
  return [
    `// Auto-generated by playwright-archaeologist at ${ts}.`,
    `// Source bundle: ${bundle}`,
    '// This file is a STARTING POINT — review assertions before using in CI.',
    '',
    "import { test, expect } from '@playwright/test';",
    '',
  ].join('\n');
}

// ---------------------------------------------------------------------------
// Smoke spec
// ---------------------------------------------------------------------------

export interface SmokeRouteInput {
  url: string;
  statusCode: number;
  title: string;
}

export interface SmokeSpecInput {
  header: string;
  targetUrl: string;
  title: string;
  routes: SmokeRouteInput[];
}

export function renderSmokeSpec(input: SmokeSpecInput): string {
  const target = escapeForSingleQuotedString(input.targetUrl);
  const titleLiteral = escapeForSingleQuotedString(input.title);

  const routeEntries = input.routes.map((r) => {
    const u = escapeForSingleQuotedString(r.url);
    return `  { url: '${u}', expectedStatus: ${r.statusCode} }`;
  }).join(',\n');

  const body = [
    input.header,
    `test('homepage loads', async ({ page }) => {`,
    `  const response = await page.goto('${target}');`,
    `  expect(response).not.toBeNull();`,
    `  expect(response!.status()).toBeLessThan(400);`,
    input.title.length > 0
      ? `  await expect(page).toHaveTitle(/${escapeForRegex(input.title)}/);`
      : `  // No title recorded in bundle — skip title assertion.`,
    `});`,
    '',
    `test.describe('key routes return expected statuses', () => {`,
    `  const expected: Array<{ url: string; expectedStatus: number }> = [`,
    routeEntries,
    `  ];`,
    '',
    `  for (const entry of expected) {`,
    `    test(\`GET \${entry.url} -> \${entry.expectedStatus}\`, async ({ page }) => {`,
    `      const response = await page.goto(entry.url);`,
    `      expect(response).not.toBeNull();`,
    `      expect(response!.status()).toBe(entry.expectedStatus);`,
    `    });`,
    `  }`,
    `});`,
    '',
  ].join('\n');

  // Suppress unused-warning from eslint consumers who enable noUnusedLocals.
  void titleLiteral;
  return body;
}

/**
 * Escape a string for inclusion in a RegExp literal. Escapes regex
 * metacharacters so matching is literal.
 */
function escapeForRegex(input: string): string {
  return escapeForSingleQuotedString(input.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
}

// ---------------------------------------------------------------------------
// Form spec
// ---------------------------------------------------------------------------

export interface FormFieldPlaceholder {
  name: string;
  /** The type-derived placeholder value to fill. */
  value: string;
  /** The raw input type, used to choose a locator strategy. */
  type: string;
}

export interface FormTestInput {
  /** Title used in `test(..)`. */
  name: string;
  /** The URL to navigate to before interacting. */
  pageUrl: string;
  /** Form action (captured in a comment for reviewer context). */
  action: string;
  /** HTTP method. Uppercased. */
  method: string;
  /** Required fields only — optional fields are intentionally skipped. */
  fields: FormFieldPlaceholder[];
  /** Submit button text if recorded. */
  submitButtonText?: string;
}

export interface FormSpecInput {
  header: string;
  pageUrl: string;
  forms: FormTestInput[];
}

/**
 * Choose a fill statement for a given form field. We fall back to
 * `getByPlaceholder` only when we do not have a name; in practice most
 * scraped forms have a name. For type="file" we do not attempt to fill.
 */
function renderFormFill(field: FormFieldPlaceholder): string {
  const name = escapeForSingleQuotedString(field.name);
  const value = escapeForSingleQuotedString(field.value);

  if (field.type === 'file') {
    return `    // Skipping file input "${name}" — emit a test-level setInputFiles() with real fixtures.`;
  }

  if (field.name.length > 0) {
    return `    await page.locator('[name="${name}"]').first().fill('${value}');`;
  }
  // Nameless input — fall back to placeholder match if we had one.
  return `    // Field has no name attribute; replace with a reviewer-chosen selector.`;
}

export function renderFormSpec(input: FormSpecInput): string {
  const url = escapeForSingleQuotedString(input.pageUrl);

  const tests = input.forms.map((f) => {
    const testName = escapeForSingleQuotedString(f.name);
    const actionComment = escapeForBlockComment(`${f.method.toUpperCase()} ${f.action || '(no action)'}`);
    const fills = f.fields.map(renderFormFill).join('\n');
    const submitHint = f.submitButtonText
      ? `'button:has-text("${escapeForSingleQuotedString(f.submitButtonText)}")'`
      : `'button[type="submit"], input[type="submit"]'`;

    const fillsBlock = fills.length > 0
      ? fills
      : '    // No required fields captured — reviewer should add explicit fills.';

    return [
      `test('${testName}', async ({ page }) => {`,
      `  // ${actionComment}`,
      `  await page.goto('${url}');`,
      `  await page.waitForLoadState('domcontentloaded');`,
      '',
      `  await test.step('fill required fields', async () => {`,
      fillsBlock,
      `  });`,
      '',
      `  const [response] = await Promise.all([`,
      `    page.waitForResponse((r) => r.request().method() !== 'OPTIONS', { timeout: 15_000 }).catch(() => null),`,
      `    page.locator(${submitHint}).first().click(),`,
      `  ]);`,
      '',
      `  if (response) {`,
      `    expect(response.status(), 'form submission should not return 5xx').toBeLessThan(500);`,
      `  }`,
      `});`,
      '',
    ].join('\n');
  }).join('\n');

  return `${input.header}\n${tests}`;
}

// ---------------------------------------------------------------------------
// Flow spec
// ---------------------------------------------------------------------------

export interface FlowStepInput {
  /** URL of the page the user is on before the step. */
  from: string;
  /** URL of the page the user lands on after the step. */
  to: string;
  /** Text of the element that triggers navigation, if recorded. */
  triggerText?: string;
  /** Navigation trigger kind (link, click, redirect, etc.). */
  trigger: string;
}

export interface FlowSpecInput {
  header: string;
  /** Flow label used in the `describe` block. */
  label: string;
  /** Ordered list of navigation steps in this flow. */
  steps: FlowStepInput[];
  /** Whether to split each step into its own test. */
  splitPerStep: boolean;
}

function renderStepBody(step: FlowStepInput): string {
  const fromUrl = escapeForSingleQuotedString(step.from);
  const toUrl = escapeForSingleQuotedString(step.to);

  // Redirects are asserted via page.goto directly; click flows need a click
  // on the captured trigger text or any <a href> pointing at `to`.
  if (step.trigger === 'redirect' || step.trigger === 'meta-refresh' || step.trigger === 'js-redirect') {
    return [
      `    const response = await page.goto('${fromUrl}');`,
      `    expect(response).not.toBeNull();`,
      `    // Expected redirect destination: ${toUrl}`,
      `    await page.waitForURL('${toUrl}', { timeout: 15_000 });`,
    ].join('\n');
  }

  const triggerText = step.triggerText && step.triggerText.trim().length > 0
    ? step.triggerText.trim().slice(0, 200)
    : '';

  if (triggerText.length > 0) {
    const safeText = escapeForSingleQuotedString(triggerText);
    return [
      `    await page.goto('${fromUrl}');`,
      `    await page.waitForLoadState('domcontentloaded');`,
      `    await page.getByText('${safeText}', { exact: false }).first().click();`,
      `    await page.waitForURL('${toUrl}', { timeout: 15_000 });`,
    ].join('\n');
  }

  return [
    `    await page.goto('${fromUrl}');`,
    `    await page.waitForLoadState('domcontentloaded');`,
    // Fallback: click the first anchor whose href ends in `to`'s pathname.
    `    await page.locator('a[href="${toUrl}"], a[href*="${extractPathQuery(step.to)}"]').first().click();`,
    `    await page.waitForURL('${toUrl}', { timeout: 15_000 });`,
  ].join('\n');
}

function extractPathQuery(url: string): string {
  try {
    const u = new URL(url);
    return escapeForSingleQuotedString(u.pathname + u.search);
  } catch {
    return escapeForSingleQuotedString(url);
  }
}

export function renderFlowSpec(input: FlowSpecInput): string {
  const label = escapeForSingleQuotedString(input.label);

  if (input.splitPerStep) {
    const stepTests = input.steps.map((step, i) => {
      const stepLabel = `step ${i + 1}: ${step.trigger} -> ${step.to}`;
      const safeLabel = escapeForSingleQuotedString(stepLabel);
      return [
        `  test('${safeLabel}', async ({ page }) => {`,
        renderStepBody(step),
        `  });`,
        '',
      ].join('\n');
    }).join('\n');

    return `${input.header}\ntest.describe('${label}', () => {\n${stepTests}});\n`;
  }

  const walkBody = input.steps.map((step, i) => {
    const stepLabel = escapeForSingleQuotedString(`step ${i + 1}: ${step.trigger} -> ${step.to}`);
    return [
      `  await test.step('${stepLabel}', async () => {`,
      renderStepBody(step),
      `  });`,
    ].join('\n');
  }).join('\n\n');

  return [
    input.header,
    `test('${label}', async ({ page }) => {`,
    walkBody,
    `});`,
    '',
  ].join('\n');
}

// ---------------------------------------------------------------------------
// API spec
// ---------------------------------------------------------------------------

export interface ApiEndpointInput {
  method: string;
  /** Concrete URL to call (first observed). */
  exampleUrl: string;
  /** Status code from the bundled exampleResponse. */
  expectedStatus: number;
  /** Content type if known. */
  contentType?: string;
}

export interface ApiSpecInput {
  header: string;
  endpoints: ApiEndpointInput[];
}

export function renderApiSpec(input: ApiSpecInput): string {
  const tests = input.endpoints.map((e) => {
    const method = e.method.toUpperCase().replace(/[^A-Z]/g, '') || 'GET';
    const url = escapeForSingleQuotedString(e.exampleUrl);
    const status = e.expectedStatus || 200;
    const contentCheck = e.contentType
      ? `  expect(response.headers()['content-type'] ?? '').toContain('${escapeForSingleQuotedString(e.contentType.split(';')[0].trim())}');`
      : `  // Response content type not recorded — no content-type assertion emitted.`;

    const name = escapeForSingleQuotedString(`${method} ${e.exampleUrl} returns ${status}`);
    return [
      `test('${name}', async ({ request }) => {`,
      `  const response = await request.fetch('${url}', { method: '${method}' });`,
      `  expect(response.status()).toBe(${status});`,
      contentCheck,
      `});`,
      '',
    ].join('\n');
  }).join('\n');

  return `${input.header}\n${tests}`;
}
